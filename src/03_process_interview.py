def time_to_seconds(t_str: str) -> float:
    """Конвертирует MM:SS или HH:MM:SS в секунды."""
    parts = list(map(int, t_str.strip().split(":")))
    if len(parts) == 2:
        return parts[0] * 60 + parts[1]
    elif len(parts) == 3:
        return parts[0] * 3600 + parts[1] * 60 + parts[2]
    return 0.0


def is_ad_or_junk(text: str) -> bool:
    lower = text.lower()
    return any(re.search(pat, lower) for pat in AD_PATTERNS)


def clean_story(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"(.)\1{5,}", r"\1\1\1", text)
    text = re.sub(r"\bбыл строй\b", "Меллстрой", text, flags=re.IGNORECASE)
    return text


def split_into_narrative_chunks(text: str, max_words: int = 150) -> list[str]:
    """
    Разбивает длинный монолог на логические связные фрагменты
    по границам предложений (чтобы не превышать контекст LLM).
    """
    sentences = re.split(r"(?<=[.!?])\s+", text)
    chunks = []
    current_chunk = []
    current_word_count = 0

    for sent in sentences:
        words = sent.split()
        if not words:
            continue
        if current_word_count + len(words) > max_words and current_chunk:
            chunks.append(" ".join(current_chunk).strip())
            current_chunk = []
            current_word_count = 0

        current_chunk.append(sent)
        current_word_count += len(words)

    if current_chunk:
        chunks.append(" ".join(current_chunk).strip())

    return [c for c in chunks if len(c.split()) >= 15]


def process_interview(json_path: str, output_path: str) -> list[dict]:
    if not os.path.exists(json_path):
        raise FileNotFoundError(f"Файл {json_path} не найден! Дождись окончания 02_transcribe.py")

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    chunks = data.get("chunks", [])
    if not chunks:
        print("[-] В транскрипте нет чанков с таймкодами!")
        return []

    print(f"[*] Загружено {len(chunks)} сегментов Whisper из интервью.")

    dialogues = []

    for start_str, end_str, question in CHAPTERS:
        t_start = time_to_seconds(start_str)
        t_end = time_to_seconds(end_str)

        # Собираем все фразы внутри интервала главы
        chapter_utterances = []
        for ch in chunks:
            ch_start = ch["start"]
            if t_start <= ch_start < t_end:
                txt = ch["text"].strip()
                if txt and not is_ad_or_junk(txt):
                    chapter_utterances.append(txt)

        if not chapter_utterances:
            continue

        raw_story = clean_story(" ".join(chapter_utterances))
        story_parts = split_into_narrative_chunks(raw_story, max_words=140)

        for i, part in enumerate(story_parts):
            user_prompt = question if i == 0 else f"Расскажи подробнее, как это было дальше?"
            dialogues.append({
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                    {"role": "assistant", "content": part},
                ]
            })

    print(f"[+] Из интервью «Вписка» собрано {len(dialogues)} развернутых историй!")

    with jsonlines.open(output_path, mode="w") as writer:
        writer.write_all(dialogues)

    return dialogues


def merge_datasets(tiktok_train_path: str, interview_path: str, final_train_path: str):
    """Объединяет 803 диалога из TikTok и истории из Вписки."""
    all_samples = []

    if os.path.exists(tiktok_train_path):
        with jsonlines.open(tiktok_train_path) as reader:
            tiktok_data = list(reader)
            all_samples.extend(tiktok_data)
            print(f"[*] TikTok-диалогов загружено: {len(tiktok_data)}")
    else:
        print(f"[!] Файл {tiktok_train_path} не найден!")

    if os.path.exists(interview_path):
        with jsonlines.open(interview_path) as reader:
            interview_data = list(reader)
            all_samples.extend(interview_data)
            print(f"[*] Историй из Вписки загружено: {len(interview_data)}")

    with jsonlines.open(final_train_path, mode="w") as writer:
        writer.write_all(all_samples)

    print("\n" + "=" * 60)
    print(f"[+] ФИНАЛЬНЫЙ ТРЕНИРОВОЧНЫЙ ДАТАСЕТ v1.0 СОБРАН: {final_train_path}")
    print(f"[+] ВСЕГО ДИАЛОГОВ: {len(all_samples)}")
    print("=" * 60)


